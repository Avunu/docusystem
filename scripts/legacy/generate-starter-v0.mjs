#!/usr/bin/env node
// Writes scripts/legacy/starter-v0.json: the sha256 of every file of the project-docs starter that the
// pilots copied (Avunu/docs, branch feat/project-docs-starter, directory Sites/project-docs-starter/template,
// commit 1820d01ccbd2a6a299f6f673381a2272a06c64dc, the last commit of that branch). The migration
// (scripts/migrate-pilot.mjs) deletes a file of a pilot only when its bytes are one of these, so that
// nothing a person changed is lost. The file is dev-only: it is not in the tarball.
//
//   node scripts/legacy/generate-starter-v0.mjs <template-dir> --commit <40-character commit> [--out <file>]
//
//   <template-dir>  the template folder of a checkout of that commit (a fresh clone; the files are read as
//                   they are, so a modified working tree gives different hashes: use a clean one).
//   --commit        the commit of the checkout, recorded in the file.
//   --out           where to write. Default: scripts/legacy/starter-v0.json next to this script.
//   --check         write nothing; exit 1 when the file on disk differs from what would be written.
//
// The 83 files are those of the template: 81 that belong in a site folder (docs-site/), and two of the
// repository's .github folder (the 121-line workflow and a Dependabot file); the migration tells them
// apart by their path.
//
// Exit codes: 0 done; 1 the file differs (--check) or the folder is not the template; 2 usage error.
import { createHash } from "node:crypto";
import { lstatSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { parseArgs } from "node:util";
import { canonicalSha256 } from "./canonical.mjs";

const HERE = import.meta.dirname;
export const SOURCE = {
  repository: "Avunu/docs",
  branch: "feat/project-docs-starter",
  path: "Sites/project-docs-starter/template",
};
/** The JSON files whose canonical hash is recorded, and the top-level keys that differ by project. */
export const CANONICAL = { "package.json": ["name"], "project.json": ["name", "url"] };
const SKIP = new Set(["node_modules", ".git", "dist", ".generated", ".docusystem"]);

/** Every file below `dir` as `/`-separated relative paths, sorted. A symbolic link is an error. */
export function listFiles(dir, prefix = "") {
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (SKIP.has(entry.name) && prefix === "") continue;
    const rel = `${prefix}${entry.name}`;
    const path = join(dir, entry.name);
    if (lstatSync(path).isSymbolicLink()) throw new Error(`${rel} is a symbolic link`);
    if (entry.isDirectory()) out.push(...listFiles(path, `${rel}/`));
    else out.push(rel);
  }
  return out.sort();
}

/** The content of starter-v0.json for the template at `dir`, recorded as of `commit`. */
export function describeStarter(dir, commit) {
  const files = {};
  for (const rel of listFiles(dir)) {
    files[rel] = createHash("sha256")
      .update(readFileSync(join(dir, ...rel.split("/"))))
      .digest("hex");
  }
  const canonical = {};
  for (const [file, ignore] of Object.entries(CANONICAL)) {
    let parsed;
    try {
      parsed = JSON.parse(readFileSync(join(dir, file), "utf8"));
    } catch (error) {
      throw new Error(`${file} is missing or is not JSON: is this the template folder?`, {
        cause: error,
      });
    }
    canonical[file] = { ignore, sha256: canonicalSha256(parsed, ignore) };
  }
  for (const needed of ["docs.config.json", ".github/workflows/docs.yml", "scripts/lib/stage.ts"]) {
    if (files[needed] === undefined)
      throw new Error(`${needed} is missing: is this the template folder?`);
  }
  return {
    note:
      "sha256 of every file of the project-docs starter that the pilots copied. scripts/migrate-pilot.mjs " +
      "deletes a file of a pilot only when its bytes are these; the others are kept and listed. " +
      "Paths under .github/ belong to the repository root, all others to the site folder. " +
      "`canonical` holds the hash of a JSON file without the keys that differ by project " +
      "(scripts/legacy/canonical.mjs). Generated by scripts/legacy/generate-starter-v0.mjs.",
    source: { ...SOURCE, commit },
    files,
    canonical,
  };
}

/** The file's text: two-space JSON, with an array of short strings on one line as the repository's formatter writes it. */
const text = (value) =>
  `${JSON.stringify(value, null, 2).replace(
    /\[\n\s+("[^"\n]*"(?:,\n\s+"[^"\n]*")*)\n\s*\]/g,
    (_match, items) => `[${items.split(/,\n\s+/).join(", ")}]`,
  )}\n`;

function main(argv) {
  let parsed;
  try {
    parsed = parseArgs({
      args: argv,
      allowPositionals: true,
      options: {
        commit: { type: "string" },
        out: { type: "string" },
        check: { type: "boolean" },
        help: { type: "boolean", short: "h" },
      },
    });
  } catch (error) {
    console.error(`generate-starter-v0: ${error.message}`);
    return 2;
  }
  const { values, positionals } = parsed;
  const usage =
    "usage: node scripts/legacy/generate-starter-v0.mjs <template-dir> --commit <40-character commit> [--out <file>] [--check]";
  if (values.help) {
    console.log(usage);
    return 0;
  }
  if (positionals.length !== 1 || !/^[0-9a-f]{40}$/.test(values.commit ?? "")) {
    console.error(usage);
    return 2;
  }
  const out = resolve(values.out ?? join(HERE, "starter-v0.json"));
  let wanted;
  try {
    wanted = text(describeStarter(resolve(positionals[0]), values.commit));
  } catch (error) {
    console.error(`generate-starter-v0: ${error.message}`);
    return 1;
  }
  if (values.check) {
    let have = null;
    try {
      have = readFileSync(out, "utf8");
    } catch {
      // absent: reported below
    }
    // compared as data: a formatter may lay the same JSON out differently
    const same = (() => {
      try {
        return JSON.stringify(JSON.parse(have ?? "")) === JSON.stringify(JSON.parse(wanted));
      } catch {
        return false;
      }
    })();
    if (!same) {
      console.error(`generate-starter-v0: ${out} differs from the template at ${values.commit}`);
      return 1;
    }
    console.log(`generate-starter-v0: ${out} matches the template at ${values.commit}`);
    return 0;
  }
  writeFileSync(out, wanted);
  console.log(
    `generate-starter-v0: wrote ${Object.keys(JSON.parse(wanted).files).length} hashes to ${out}`,
  );
  return 0;
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) {
  process.exitCode = main(process.argv.slice(2));
}

#!/usr/bin/env node
// Migrates a repository that carries a copy of the project-docs starter (a docs-site/ with its own build
// scripts, components and Bun lockfile, and a 121-line workflow) to the thin shell of @avunu/docusystem
// (section 10.4 of the architecture decision record). Dev-only: it is not in the tarball, and it is deleted
// once the pilots have migrated.
//
//   node scripts/migrate-pilot.mjs <clone> [options]
//
//   <clone>                    the root of a clone of the repository (a folder with .git). The tool works on
//                              the files only: it NEVER runs git. You review `git status`, then commit.
//   --write                    apply the plan. The default is a dry run that changes nothing and lists
//                              every file it would delete, create or update.
//   --diff                     also print the text of every create and update.
//   --site-dir <dir>           the site folder, relative to the clone. Default: docs-site
//   --workflow-sha <sha>       the 40-character commit of the release tag that the two caller workflows are
//                              pinned to: `git ls-remote https://github.com/Avunu/docusystem
//                              'refs/tags/v<version>^{}' refs/tags/v<version>` (the peeled line, else the
//                              plain one). Required with --write; a dry run shows a placeholder.
//   --package-version <x.y.z>  the release being adopted: the `# vX.Y.Z` comment of the pins and the base of
//                              the dependency range. Default: the version in this repository's package.json.
//   --range <range>            the dependency range written to package.json. Default: ^<major>.<minor>.0
//   --json                     print the plan as JSON on stdout (the report goes to stderr).
//
// What it does (steps 1 to 6 of 10.4; step 7, `npm install` and the check, is yours and is printed at the end):
//
//   1. deletes every file of the site folder whose bytes are those of the starter at its last commit
//      (scripts/legacy/starter-v0.json, 83 hashes), the Bun lockfile, project.json when it differs from the
//      starter's only in `name` and `url`, and public/CNAME when it holds the configured domain. A starter
//      file that has been changed is kept and listed.
//   2. turns docs.config.json into docusystem.config.json (same values, `$schema` added).
//   3. writes package.json (one dependency, three scripts), .gitignore and the two caller workflows,
//      replacing the starter's workflow, pinned to --workflow-sha.
//   4. converts the Bun entry of .github/dependabot.yml to npm, in place.
//   5. in dependabot-auto-merge.yml, turns `dependabot/bun/<site>` into `dependabot/npm_and_yarn/<site>`.
//   6. LISTS, and never deletes, what remains: files that differ from the starter's, files the starter never
//      had, formatter and hook settings that mention the site folder, and the advice that needs a person.
//
// It reuses the package's own helpers (the files `docusystem init` writes), from `dist/`: run
// `npm run build` first. Everything is computed before anything is written, and a plan with an error
// writes nothing. Running it again over a migrated clone changes nothing.
//
// Exit codes: 0 the plan was made (and applied with --write); 1 the plan has an error, or a write failed;
// 2 usage error.
import { createHash } from "node:crypto";
import { existsSync, lstatSync, readdirSync, readFileSync, rmdirSync, rmSync } from "node:fs";
import { dirname, isAbsolute, join, relative, resolve, sep } from "node:path";
import { pathToFileURL } from "node:url";
import { parseArgs } from "node:util";
import { canonicalize, canonicalSha256 } from "./legacy/canonical.mjs";

const ROOT = resolve(import.meta.dirname, "..");
export const PACKAGE = "@avunu/docusystem";
export const LEGACY_FILE = join(ROOT, "scripts", "legacy", "starter-v0.json");
/** What a dry run pins the workflows to when no commit is given. */
export const PLACEHOLDER_SHA = "0".repeat(40);
const SCHEMA = "./node_modules/@avunu/docusystem/config.schema.json";
const SCRIPTS = { dev: "docusystem dev", build: "docusystem build", check: "docusystem check" };
const IDENTITY = ["name", "tagline", "slug", "platform", "repo", "domain", "license"];
const CONFIG_KEYS = [...IDENTITY, "branch", "docs", "theme", "images", "jx"];
const WORKFLOWS = ["docs.yml", "docs-publish.yml"];
const WORKFLOW_DIR = ".github/workflows";
/** Files of the starter's template that are the repository's, not the site folder's, or that get special care. */
const SPECIAL = new Set([
  ".github/dependabot.yml",
  ".github/workflows/docs.yml",
  ".gitignore",
  "docs.config.json",
  "package.json",
  "project.json",
  "public/CNAME",
]);
/** The Bun lockfiles: the shell's is package-lock.json. */
const BUN_LOCKS = ["bun.lock", "bun.lockb"];
/** Generated by the starter's postinstall (`jx schema`) and by its build; its .gitignore listed them. */
const GENERATED = ["project.schema.json", "document.schema.json", ".generated"];
/** Never listed as leftovers: installed or built, and ignored by the shell's own .gitignore. */
const IGNORED_DIRS = new Set(["node_modules", "dist", ".docusystem"]);
/** The shell's own files in the site folder. */
const SHELL = new Set([
  "docusystem.config.json",
  "package.json",
  ".gitignore",
  "package-lock.json",
]);

